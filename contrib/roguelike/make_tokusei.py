#!/usr/bin/env python3
"""Writes datastore/data/tokusei/tokusei_stephens_clock.xml.

The server only knows the IDs (see server/channel/src/StephensClock.cpp):

    9100001          enemy max HP +5% (stacked)
    9100002          enemy damage +5% (stacked)
    9100011          XP +5% (stacked)
    9100012          Macca and Magnetite +5% (stacked)
    9100100 + m*5+s  modifier m, slot s: 0 everyone, 1 enemies and partner
                     demons, 2 enemies, 3 players, 4 players until the
                     clock stops
    9100500 + b*2    boon b (+1: until the clock stops)

What each one does is defined here, so the numbers can be changed without
rebuilding the server. Run this script again after editing it.
"""
import os

BASE = 9100000
P = 1   # percent of the base value
P2 = 2  # percent applied last (after flat bonuses and the enemy HP bonus)
N = 0   # flat number

DAMAGE = ('RATE_CLSR', 'RATE_LNGR', 'RATE_SPELL')
TAKEN = ('RATE_CLSR_TAKEN', 'RATE_LNGR_TAKEN', 'RATE_SPELL_TAKEN')


def all_of(tables, value, kind=P):
    return [(t, value, kind) for t in tables]


TOKUSEI = [
    ('Enemy max HP +5% per stack', BASE + 1, [('HP_MAX', 5, P2)]),
    ('Enemy damage +5% per stack', BASE + 2, all_of(DAMAGE, 5)),
    ('XP +5% per stack', BASE + 11, [('RATE_XP', 5, P)]),
    ('Macca and Magnetite +5% per stack', BASE + 12,
     [('RATE_MACCA', 5, P), ('RATE_MAG', 5, P)]),
]


def modifier(m, slot, name, values):
    TOKUSEI.append((f'Rule {m}: {name}', BASE + 100 + m * 5 + slot, values))


def boon(b, name, values, reward=False):
    TOKUSEI.append((f'Boon {b}: {name}', BASE + 500 + b * 2 + (1 if reward else 0),
                    values))


EVERYONE, DEMONS, ENEMIES, PLAYERS, REWARD = range(5)

modifier(1, EVERYONE, 'Blazing Hour', [('BOOST_FIRE', 50, N)])
modifier(2, EVERYONE, 'Frozen Hour', [('BOOST_ICE', 50, N)])
modifier(3, EVERYONE, 'Thunder Hour', [('BOOST_ELEC', 50, N)])
modifier(4, EVERYONE, 'Gale Hour', [('BOOST_FORCE', 50, N)])
modifier(5, EVERYONE, 'Hour of Steel', [('RATE_CLSR', 40, P)])
modifier(6, EVERYONE, 'Hour of Powder', [('RATE_LNGR', 40, P)])
modifier(7, EVERYONE, 'Hour of Sorcery', [('RATE_SPELL', 40, P)])
# The -kaja rules give the stats of the real buff at its full 4 stacks.
# (A real constant status is not used: the server would then strip the
# normal buff from everyone who is not in a clock run.)
modifier(8, DEMONS, 'Swift Demons (Sukukaja x4)',
         [('CRITICAL', 60, N), ('CRIT_DEF', 60, N)])
modifier(9, DEMONS, 'Mighty Demons (Tarukaja x4)',
         [('CLSR', 32, N), ('LNGR', 32, N)])
modifier(10, DEMONS, 'Arcane Demons (Makakaja x4)',
         [('SPELL', 32, N), ('SUPPORT', 32, N)])
modifier(11, DEMONS, 'Guarded Demons (Rakukaja x4)', [('PDEF', 20, N)])
modifier(12, EVERYONE, 'Hour of Haste',
         [('CHANT_TIME', -30, P), ('COOLDOWN_TIME', -30, P)])
modifier(13, EVERYONE, 'Killing Hour', [('FINAL_CRIT_CHANCE', 20, N)])
modifier(14, EVERYONE, 'Hour of Vigor',
         [('HP_REGEN', 200, P), ('MP_REGEN', 200, P)])
modifier(15, ENEMIES, 'Golden Hour', [('HP_MAX', 30, P2)])
modifier(15, REWARD, 'Golden Hour',
         [('RATE_MACCA', 60, P), ('RATE_MAG', 60, P)])
modifier(16, ENEMIES, "Scholar's Hour", all_of(DAMAGE, 15))
modifier(16, REWARD, "Scholar's Hour", [('RATE_XP', 60, P)])
modifier(17, EVERYONE, 'Glass Hour', all_of(DAMAGE, 35))
modifier(18, EVERYONE, 'Fleet Hour', [('MOVE2', 25, P)])

boon(1, 'Might', all_of(DAMAGE, 12))
boon(2, 'Aegis', all_of(TAKEN, -10))
boon(3, 'Vitality', [('HP_MAX', 20, P)])
boon(4, 'Spirit', [('MP_MAX', 20, P), ('MP_REGEN', 50, P)])
boon(5, 'Focus', [('CHANT_TIME', -10, P), ('COOLDOWN_TIME', -10, P)])
boon(6, 'Precision', [('FINAL_CRIT_CHANCE', 8, N)])
boon(7, 'Fleetness', [('MOVE2', 15, P)])
boon(8, 'Fortune', [('RATE_MACCA', 25, P), ('RATE_MAG', 25, P)], reward=True)
boon(9, 'Insight', [('RATE_XP', 25, P)], reward=True)
# Boons 10 (Borrowed Time) and 11 (Plunder) are handled by the server.


def main():
    out = ['<objgen>',
           "    <!-- Stephen's Clock. Generated by "
           'contrib/roguelike/make_tokusei.py, edit that instead. -->']
    for label, tid, values in TOKUSEI:
        out.append(f'    <!-- {label} -->')
        out.append('    <object name="Tokusei">')
        out.append(f'        <member name="ID">{tid}</member>')
        out.append('        <member name="CorrectValues">')
        for table, value, kind in values:
            out.append('            <element>')
            out.append('                <object>')
            out.append(f'                    <member name="ID">{table}</member>')
            out.append(f'                    <member name="Value">{value}</member>')
            if kind:
                out.append(f'                    <member name="Type">{kind}</member>')
            out.append('                </object>')
            out.append('            </element>')
        out.append('        </member>')
        out.append('    </object>')
    out.append('</objgen>')

    here = os.path.dirname(os.path.abspath(__file__))
    path = os.path.join(here, '..', '..', 'datastore', 'data', 'tokusei',
                        'tokusei_stephens_clock.xml')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(f'{len(TOKUSEI)} tokusei written to {os.path.normpath(path)}')


if __name__ == '__main__':
    main()
