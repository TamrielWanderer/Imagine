#!/usr/bin/env python3
"""Assemble shortcut_bars.asm (needs nasm) and write shortcut_bars_code.py,
which shortcut_bars_patch.py imports (so players don't need nasm)."""
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SYMBOLS = ['dbg', 'load_macros', 'poll_macros', 'cave_init', 'cave_ss_entry', 'cave_ss_exit', 'cave_evt',
           'cave_keys', 'cave_act', 'cave_find_ebp', 'cave_find_edi']


def main():
    src = os.path.join(HERE, 'shortcut_bars.asm')
    with tempfile.TemporaryDirectory() as tmp:
        asm = os.path.join(tmp, 'sb.asm')
        mp = os.path.join(tmp, 'sb.map')
        out = os.path.join(tmp, 'sb.bin')
        with open(src) as f:
            text = f.read()
        with open(asm, 'w') as f:
            f.write(f'[map symbols {mp}]\n' + text)
        subprocess.run(['nasm', '-f', 'bin', asm, '-o', out], check=True)
        code = open(out, 'rb').read()
        syms = {}
        for line in open(mp):
            m = re.match(r'\s*([0-9A-F]+)\s+[0-9A-F]+\s+(\S+)$', line)
            if m and m.group(2) in SYMBOLS:
                syms[m.group(2)] = int(m.group(1), 16)
    missing = set(SYMBOLS) - set(syms)
    if missing:
        sys.exit(f'symbols not found: {missing}')
    dst = os.path.join(HERE, 'shortcut_bars_code.py')
    with open(dst, 'w') as f:
        f.write('# Generated by build_shortcut_bars.py from shortcut_bars.asm.\n')
        f.write('CODE_VA = 0x1400000\n')
        f.write('SYMBOLS = {\n')
        for k in SYMBOLS:
            f.write(f"    '{k}': {syms[k]:#x},\n")
        f.write('}\n')
        f.write('CODE = bytes.fromhex(\n')
        h = code.hex()
        for i in range(0, len(h), 96):
            f.write(f"    '{h[i:i + 96]}'\n")
        f.write(')\n')
    print(f'{len(code)} bytes, written {dst}')


if __name__ == '__main__':
    main()
